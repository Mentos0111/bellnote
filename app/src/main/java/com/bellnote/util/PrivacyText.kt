一、不收集什么
· 不要求注册、不收集手机号、邮箱、姓名、通讯录、位置、设备标识（IMEI/Android ID/广告 ID 都不读）。
· 没有广告 SDK、没有统计 SDK，不做用户画像，不向任何第三方出售数据。

二、数据存在哪
· 待办内容、提醒设置、配色偏好都存在手机本地的应用私有目录（SQLite 数据库与 SharedPreferences），只有本应用能读。
· 截图识别用的 DeepSeek API Key 也以明文存在本地偏好文件里，不上传、不做二次分发。请自行保管好手机。
· 卸载本应用，上述数据一并删除。设置里也提供「导出 .ics」「备份账本」用于你自己带走数据。

三、什么时候会联网
只有两种情况：
1. 你主动点「识别这张图」时，截图会被发送到 DeepSeek 的接口（地址由你在设置里填写的服务商决定），用于把图片里的文字解析成待办。请求里带有你填写的 API Key，这是 DeepSeek 校验身份所需的凭据。这一步的数据处理遵循 DeepSeek 的隐私政策，与本应用无关。
2. 如果你在设置里填了 ntfy 主题（第三方推送，可选），本应用会每 15 分钟向该 ntfy 服务器拉取一次新消息，用于把电脑上发出的待办同步进手机日历。不填这个主题，本应用完全不访问网络。
除此之外没有任何网络请求，没有后台静默上传。

四、权限都用在哪
· 日历读写：把待办写成系统日历事件，并读取你现有的日历以便对账。
· 通知：推送写入结果、对账差异提醒。可以随时在系统里关掉。
· 读取相册（可选）：截图后主动提醒你识别；不授权也能手动选图。
· 无障碍服务（可选，仅「侧边栏截屏记」用到）：让你在别的应用里点一下就能截屏。不开也能用其他入口。
· 开机启动：重启后重新排上定时对账与推送补查。

五、你的控制权
· 每一项权限都能在系统设置里随时关闭；关掉后对应功能失效，其它功能不受影响。
· 关掉「自动导入」后，推送不会再写进日历。
· 卸载即删除全部本地数据；导出功能可随时把数据带走。

六、未成年人
本应用不面向未成年人单独提供服务，也不主动收集未成年人信息。

七、变更与联系
· 政策如有实质变化，会在新版本更新说明里写明日期。
· 有问题或想删除数据，可通过应用仓库的 Issue 反馈（GitHub: Mentos0111/bellnote）。
